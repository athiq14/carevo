"""
Strict, secure JSON parser for LLM structured outputs.
Handles standard JSON, single markdown-fenced blocks, whitespace, and root type enforcement.
Rejects truncated data, multiple ambiguous objects, and plain-text responses without eval().
"""
import json
import re
from typing import Any, Optional, Type, Union

from core.llm.exceptions import redact_secrets
from core.llm.structured.exceptions import JSONParsingError


def extract_json_text(raw_text: str) -> str:
    """
    Extract JSON text payload from raw LLM output.
    Supports standard JSON or a single markdown code fence block (```json ... ``` or ``` ... ```).

    Raises:
        JSONParsingError: If text is blank or contains multiple ambiguous code blocks.
    """
    if not raw_text or not raw_text.strip():
        raise JSONParsingError(
            message="LLM output is empty or contains only whitespace.",
            raw_content=None,
        )

    # Strip whitespace and Unicode BOM
    cleaned = raw_text.strip().lstrip("\ufeff")

    # Match all markdown code fence blocks
    fence_pattern = re.compile(r"```(?:json)?\s*([\s\S]*?)\s*```", re.IGNORECASE)
    fences = fence_pattern.findall(cleaned)

    if len(fences) > 1:
        raise JSONParsingError(
            message=f"Ambiguous LLM output: detected {len(fences)} separate markdown code blocks. Expected exactly one.",
            raw_content=None,
        )

    if len(fences) == 1:
        # Extract only the content inside the single code fence
        extracted = fences[0].strip()
        if not extracted:
            raise JSONParsingError(
                message="Markdown code fence in LLM output is empty.",
                raw_content=None,
            )
        return extracted

    # No code fences: verify it is not accompanied by multiple raw JSON root objects
    return cleaned


def parse_json_payload(
    raw_text: str,
    expected_root_type: Union[Type[Any], tuple[Type[Any], ...]] = dict,
    provider_name: Optional[str] = None,
    model_name: Optional[str] = None,
    attempts: int = 1,
) -> Any:
    """
    Parse and validate raw LLM text into a Python object with root type checking.

    Args:
        raw_text: Raw string generated by the LLM.
        expected_root_type: Expected Python type of root container (default: dict).
        provider_name: Name of provider for error traceability.
        model_name: Name of model for error traceability.
        attempts: Attempt count for error traceability.

    Returns:
        Parsed Python dictionary or structure.

    Raises:
        JSONParsingError: If JSON is invalid, truncated, has multiple objects, or has wrong root type.
    """
    try:
        json_str = extract_json_text(raw_text)
    except JSONParsingError as err:
        err.provider_name = provider_name
        err.model_name = model_name
        err.attempts = attempts
        raise err

    # Perform strict JSON decoding
    try:
        data = json.loads(json_str)
    except json.JSONDecodeError as exc:
        raise JSONParsingError(
            message=f"Invalid or truncated JSON ({exc.msg} at line {exc.lineno}, col {exc.colno}).",
            provider_name=provider_name,
            model_name=model_name,
            raw_content=None,
            attempts=attempts,
            parse_error=exc,
        ) from exc
    except Exception as exc:
        raise JSONParsingError(
            message=f"Failed to decode JSON payload: {redact_secrets(str(exc))}",
            provider_name=provider_name,
            model_name=model_name,
            raw_content=None,
            attempts=attempts,
            parse_error=exc,
        ) from exc

    # Enforce expected root container type (e.g. dict for Pydantic BaseModel)
    if not isinstance(data, expected_root_type):
        expected_name = (
            ", ".join(t.__name__ for t in expected_root_type)
            if isinstance(expected_root_type, tuple)
            else expected_root_type.__name__
        )
        actual_name = type(data).__name__
        raise JSONParsingError(
            message=f"Incorrect root JSON type: expected {expected_name}, got {actual_name}.",
            provider_name=provider_name,
            model_name=model_name,
            raw_content=None,
            attempts=attempts,
        )

    return data

